/** Standalone HTML document used for Word and PDF. */
export function toPrintHtml(doc: AgentDocument): string {
  const blocks = parse(doc.body);
  // The sheet header already carries the title; drop a leading H1 that repeats it.
  const body = blocks[0]?.type === 'heading' && blocks[0].level === 1 ? blocks.slice(1) : blocks;
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const date = new Date(doc.createdAt).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });

  return `<!doctype html>
<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word">
<head><meta charset="utf-8"><title>${esc(doc.title)}</title><style>${PRINT_CSS}</style></head>
<body>
<div class="brandbar"><div class="brand">iTOP<span>.</span></div>
<div class="meta">${DOC_TYPE_LABEL[doc.procedure]} · Version ${doc.version ?? 1} · ${date}</div></div>
<h1>${esc(doc.title)}</h1>
${doc.guardrail.flags.length ? `<div class="flags"><strong>Needs review:</strong> ${doc.guardrail.flags.map(esc).join('; ')}</div>` : ''}
${toHtml(body)}
<div class="foot">${footerLines(doc)
    .map((l) => `<p>${esc(l)}</p>`)
    .join('')}<p>Generated by the iTOP Agent (demo). Clinical content requires clinician review before use.</p></div>
</body></html>`;
}

function download(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function downloadWord(doc: AgentDocument) {
  // Word opens HTML saved as .doc with formatting intact. Real .docx comes from the server.
  download(new Blob(['﻿', toPrintHtml(doc)], { type: 'application/msword' }), `${fileBase(doc)}.doc`);
}

export function downloadMarkdown(doc: AgentDocument) {
  download(new Blob([toMarkdown(doc)], { type: 'text/markdown;charset=utf-8' }), `${fileBase(doc)}.md`);
}

/** Opens the system print dialog on the formatted page; "Save as PDF" lives there. */
export function printPdf(doc: AgentDocument) {
  const frame = document.createElement('iframe');
  frame.style.cssText = 'position:fixed;width:0;height:0;border:0;right:0;bottom:0';
  frame.srcdoc = toPrintHtml(doc);
  frame.onload = () => {
    frame.contentWindow?.focus();
    frame.contentWindow?.print();
    setTimeout(() => frame.remove(), 60_000);
  };
  document.body.appendChild(frame);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.cssText = 'position:fixed;opacity:0';
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  }
}

export async function shareDoc(doc: AgentDocument): Promise<void> {
  const md = toMarkdown(doc);
  try {
    const file = new File([toPrintHtml(doc)], `${fileBase(doc)}.doc`, { type: 'application/msword' });
    if (navigator.canShare?.({ files: [file] })) {
      await navigator.share({ title: doc.title, text: doc.title, files: [file] });
      return;
    }
  } catch (e) {
    if ((e as Error).name === 'AbortError') return;
  }
  await navigator.share({ title: doc.title, text: md });
}
