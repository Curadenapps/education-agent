/**
 * Document exports. In the prototype these run in the browser; in production the
 * server (Phase D) should produce real .docx and .pdf files with the same layout.
 */
import { DOC_TYPE_LABEL, type AgentDocument } from '../agent';
import { parse, toHtml } from './markdown';

/** Embedded viewers (e.g. the published preview link) block downloads, printing and sharing. */
export const isEmbedded = (() => {
  try {
    return window.self !== window.top;
  } catch {
    return true;
  }
})();

export const canShare = !isEmbedded && typeof navigator.share === 'function';

export const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[—–]/g, '-')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);

export const fileBase = (doc: AgentDocument) => `${slug(doc.title)}_${doc.createdAt.slice(0, 10)}${doc.version && doc.version > 1 ? `_v${doc.version}` : ''}`;

const footerLines = (doc: AgentDocument) => [
  `Guardrail: ${doc.guardrail.status}${doc.guardrail.flags.length ? ' — ' + doc.guardrail.flags.join('; ') : ''}`,
  `Sources: ${doc.sources.map((s) => (s.kind === 'drive' ? `${s.title} (Drive)` : s.title)).join(' · ')}`,
  `Saved: ${doc.savedPath ?? 'not saved'}`,
];

/** Markdown with the standard footer from agents/education-agent-procedures.md. */
export function toMarkdown(doc: AgentDocument): string {
  return `${doc.body.trim()}\n\n---\n\n${footerLines(doc).join('  \n')}\n`;
}

